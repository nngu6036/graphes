def _sampling_times(total_steps: int, sample_steps: int) -> list[int]:
    if sample_steps < 1 or sample_steps > total_steps:
        raise ValueError("attribute sample_steps must be in [1, total_steps]")
    times = np.rint(np.linspace(total_steps, 0, sample_steps + 1)).astype(int).tolist()
    if times[0] != total_steps or times[-1] != 0:
        raise AssertionError("attribute sampling schedule endpoints are incorrect")
    if any(next_time >= time for time, next_time in zip(times, times[1:])):
        raise ValueError("attribute sampling schedule must strictly decrease")
    return times


def _initial_attribute_state(
    flags: torch.Tensor,
    support: torch.Tensor,
    node_noise: MarginalNoise,
    bond_noise: MarginalNoise,
    generator: torch.Generator,
) -> tuple[torch.Tensor, torch.Tensor]:
    b, n = flags.shape
    node_probs = node_noise.marginal.view(1, 1, -1).expand(b, n, -1)
    nodes = draw_categories(node_probs, generator).masked_fill(~flags.bool(), 0)
    edge_probs = bond_noise.marginal.view(1, 1, 1, -1).expand(
        b, n, n, -1
    )
    bonds = _sample_upper_categories(edge_probs, support, generator)
    return nodes, bonds


def _reverse_fixed_bonds(
    clean_probs: torch.Tensor,
    current: torch.Tensor,
    support: torch.Tensor,
    noise: MarginalNoise,
    t: torch.Tensor,
    s: torch.Tensor,
    generator: torch.Generator,
) -> tuple[torch.Tensor, torch.Tensor]:
    if clean_probs.shape[:-1] != support.shape:
        raise ValueError("Bond clean probabilities and support differ")
    posterior = torch.zeros_like(clean_probs)
    if bool(support.any()):
        tv = t[:, None, None].expand_as(current)[support]
        sv = s[:, None, None].expand_as(current)[support]
        posterior[support] = noise.reverse_probs(
            clean_probs[support], current[support], tv, sv
        )
    return _sample_upper_categories(posterior, support, generator), posterior


def _attribute_diffusion_decode(
    model: HybridAttributedSpectrumPPGNScore,
    topology: torch.Tensor,
    flags: torch.Tensor,
    sizes: torch.Tensor,
    spectral_transform: Mapping[str, Any],
    vocab: GraphCategoryVocabulary,
    attributed_cfg: Mapping[str, Any],
    diffusion_cfg: Mapping[str, Any],
    diffusion_schema: Mapping[str, Any],
    *,
    generator: torch.Generator,
) -> tuple[
    torch.Tensor,
    torch.Tensor,
    dict[str, torch.Tensor],
    list[dict[str, Any]],
    list[list[dict[str, Any]]],
]:
    device = topology.device
    b, n, _ = topology.shape
    support = topology.bool()
    clean_x = degree_features(
        topology.to(torch.float32), flags, model.max_feat_num
    )
    clean_lam, clean_u = _laplacian_eigh_padded(
        topology.to(torch.float32), sizes.to(torch.long)
    )
    clean_state = _operator_eigenvalues_to_spectral_state(
        clean_lam,
        flags,
        spectral_operator="combinatorial_laplacian",
        spectral_transform=spectral_transform,
    )
    schedule, node_noise, bond_noise = _attribute_noise_models(
        diffusion_schema, diffusion_cfg, device
    )
    times = _sampling_times(
        int(diffusion_cfg["steps"]),
        int(diffusion_cfg.get("sample_steps", diffusion_cfg["steps"])),
    )
    node_state, bond_state = _initial_attribute_state(
        flags, support, node_noise, bond_noise, generator
    )
    per_graph = [
        {
            "attribute_reverse_steps": len(times) - 1,
            "node_category_change_count": 0,
            "bond_category_change_count": 0,
            "topology_preserved": True,
        }
        for _ in range(b)
    ]
    trajectories: list[list[dict[str, Any]]] = [[] for _ in range(b)]
    final_output: dict[str, torch.Tensor] | None = None
    endpoint_node_posterior: torch.Tensor | None = None
    endpoint_bond_posterior: torch.Tensor | None = None
    atom_masks: torch.Tensor | None = None
    bond_rows: list[dict[str, Any]] | None = None

    for current_time, next_time in zip(times, times[1:]):
        t = torch.full((b,), current_time, dtype=torch.long, device=device)
        s = torch.full((b,), next_time, dtype=torch.long, device=device)
        node_input, edge_input = model.categorical_attribute_inputs(
            flags, support, node_state, bond_state
        )
        output = model.forward_attributes(
            clean_x,
            topology.to(torch.float32),
            flags,
            clean_u,
            clean_state,
            node_attr=node_input,
            edge_attr=edge_input,
            attribute_time=t.to(torch.float32) / float(diffusion_cfg["steps"]),
        )
        clean_node_probs = torch.softmax(output["node_logits"], dim=-1)
        clean_bond_probs = torch.softmax(output["edge_logits"], dim=-1)
        node_posterior = node_noise.reverse_probs(
            clean_node_probs, node_state, t[:, None].expand_as(node_state),
            s[:, None].expand_as(node_state)
        )
        if next_time > 0:
            new_nodes = draw_categories(node_posterior, generator).masked_fill(
                ~flags.bool(), 0
            )
            new_bonds, _ = _reverse_fixed_bonds(
                clean_bond_probs,
                bond_state,
                support,
                bond_noise,
                t,
                s,
                generator,
            )
        else:
            # Exact categorical posterior first, then the intrinsic constrained
            # endpoint sampler.  The constraints cannot modify topology.
            _, endpoint_bond_posterior = _reverse_fixed_bonds(
                clean_bond_probs,
                bond_state,
                support,
                bond_noise,
                t,
                s,
                generator,
            )
            endpoint_node_posterior = node_posterior
            decode_cfg = dict(attributed_cfg.get("decode", {}) or {})
            validate_decode_config(
                decode_cfg,
                vocab.node_values,
                vocab.edge_values,
                node_attribute=vocab.node_attribute,
                edge_attribute=vocab.edge_attribute,
            )
            new_nodes, atom_masks = sample_atoms(
                torch.log(node_posterior.clamp_min(1.0e-30)),
                support,
                flags,
                vocab.node_values,
                decode_cfg,
                generator,
            )
            new_bonds, bond_rows = sample_bonds(
                torch.log(endpoint_bond_posterior.clamp_min(1.0e-30)),
                support,
                flags,
                new_nodes,
                vocab.node_values,
                vocab.edge_values,
                decode_cfg,
                generator,
            )
        node_changes = ((new_nodes != node_state) & flags.bool()).sum(dim=1)
        bond_changes = (
            (new_bonds != bond_state)
            & support
            & torch.ones_like(support).triu(1)
        ).sum(dim=(1, 2))
        for row_index in range(b):
            per_graph[row_index]["node_category_change_count"] += int(
                node_changes[row_index]
            )
            per_graph[row_index]["bond_category_change_count"] += int(
                bond_changes[row_index]
            )
            if bool(diffusion_cfg.get("save_trajectory", False)):
                trajectories[row_index].append({
                    "from_t": int(current_time),
                    "to_t": int(next_time),
                    "node_categories": new_nodes[row_index].detach().cpu().tolist(),
                    "bond_categories": new_bonds[row_index].detach().cpu().tolist(),
                })
        node_state, bond_state = new_nodes, new_bonds
        final_output = output

    if final_output is None or endpoint_node_posterior is None or endpoint_bond_posterior is None:
        raise AssertionError("Attribute diffusion did not reach the clean endpoint")
    if atom_masks is None or bond_rows is None:
        raise AssertionError("Endpoint constraints were not evaluated")
    endpoint_rows = decoding_diagnostics(
        support,
        flags,
        node_state,
        bond_state,
        vocab.node_values,
        vocab.edge_values,
        atom_masks,
        bond_rows,
    )
    for row, endpoint in zip(per_graph, endpoint_rows):
        row.update(endpoint)
        row["attribute_diffusion_steps"] = int(diffusion_cfg["steps"])
        row["attribute_sampling_steps"] = len(times) - 1
        row["edge_head_includes_no_edge"] = False
        row["endpoint_constraint"] = "final_reverse_transition"

    # A final clean-state pass provides summary predictions conditioned on the
    # actually serialized categories.  It does not resample or modify anything.
    final_node_input, final_edge_input = model.categorical_attribute_inputs(
        flags, support, node_state, bond_state
    )
    final_output = model.forward_attributes(
        clean_x,
        topology.to(torch.float32),
        flags,
        clean_u,
        clean_state,
        node_attr=final_node_input,
        edge_attr=final_edge_input,
        attribute_time=torch.zeros((b,), device=device),
    )
    final_output["endpoint_node_posterior"] = endpoint_node_posterior
    final_output["endpoint_bond_posterior"] = endpoint_bond_posterior
    return node_state, bond_state, final_output, per_graph, trajectories


def generate(
    wrapper,
    request: GenerateRequest,
    state: Mapping[str, Any],
    manifest: Mapping[str, Any],
    options: Mapping[str, Any],
) -> GenerationArtifacts:
    del manifest
    validate_options(options)
    if state.get("format") != CHECKPOINT_FORMAT:
        raise RuntimeError(
            f"Expected {CHECKPOINT_FORMAT}, found {state.get('format')!r}"
        )
    if (
        state.get("attribute_diffusion_training_contract")
        != ATTRIBUTE_DIFFUSION_TRAINING_CONTRACT
    ):
        raise RuntimeError("Checkpoint does not satisfy the hybrid attribute contract")
    layout = request.run.layout
    target = layout.generation_dir(request.resolved_generation_id)
    ArtifactLayout.require_available(target, overwrite=request.overwrite)
    if request.num_graphs < 1:
        raise ValueError("num_graphs must be positive")
    batch_size = int(options.get("generation_batch_size", 128))
    if batch_size < 1:
        raise ValueError("generation_batch_size must be positive")
    device = _resolve_device(options.get("runtime", {}))
    _seed_everything(request.generation_seed)
    vocab = GraphCategoryVocabulary.from_dict(dict(state["vocabulary"]))
    model_x, model_lam = _build_models(
        dict(state["model_config"]),
        dict(state["topology_summary"]),
        dict(state["attribute_summary"]),
        device,
    )
    use_ema = bool(options.get("sample", {}).get("use_ema", False))
    model_x.load_state_dict(state["ema_x_state" if use_ema else "model_x_state"])
    model_lam.load_state_dict(
        state["ema_spectrum_state" if use_ema else "model_spectrum_state"]
    )
    model_x.eval()
    model_lam.eval()
    sde_x, sde_lam = _make_sdes({"sde": state["sde"]}, device)
    sample_cfg = copy.deepcopy(dict(state["sample"]))
    sample_cfg.update(dict(options.get("sample", {})))
    separate_rng = bool(sample_cfg.get("separate_attribute_rng", True))
    rng, topology_generator, attribute_generator, attribute_seed = (
        hierarchical._generation_rngs(
            request.generation_seed, device, separate_rng
        )
    )
    basis_adj = torch.tensor(
        np.asarray(state["basis_adjacencies"]), dtype=torch.float32
    )
    basis_n = torch.tensor(
        np.asarray(state["basis_num_nodes"]), dtype=torch.long
    )
    spectral_transform = dict(state["spectral_transform"])
    threshold = float(sample_cfg.get("threshold", 0.5))
    attr_cfg = copy.deepcopy(dict(state["attributed_config"]))
    runtime_attr = dict(options.get("attributed", {}) or {})
    if "decode" in runtime_attr:
        attr_cfg["decode"] = _deep_update(
            dict(attr_cfg.get("decode", {}) or {}),
            dict(runtime_attr.get("decode", {}) or {}),
        )
    validate_decode_config(
        dict(attr_cfg.get("decode", {}) or {}),
        vocab.node_values,
        vocab.edge_values,
        node_attribute=vocab.node_attribute,
        edge_attribute=vocab.edge_attribute,
    )
    diffusion_cfg = copy.deepcopy(dict(state["attribute_diffusion_config"]))
    runtime_diffusion = dict(options.get("attribute_diffusion", {}) or {})
    for key in ("sample_steps", "save_trajectory"):
        if key in runtime_diffusion:
            diffusion_cfg[key] = runtime_diffusion[key]
    if int(diffusion_cfg.get("sample_steps", 0)) > int(diffusion_cfg["steps"]):
        raise ValueError("attribute_diffusion.sample_steps cannot exceed trained steps")
    diffusion_schema = dict(state["attribute_diffusion_schema"])

    graphs: list[nx.Graph] = []
    topology_graphs: list[nx.Graph] = []
    continuous: list[np.ndarray] = []
    spectra: list[np.ndarray] = []
    basis_indices: list[int] = []
    topology_predictions: list[dict[str, Any]] = []
    typed_predictions: list[dict[str, Any]] = []
    combined_predictions: list[dict[str, Any]] = []
    attribute_rows: list[dict[str, Any]] = []
    topology_hashes: list[str] = []
    trajectories: list[list[dict[str, Any]]] = []
    started = time.monotonic()

    with torch.no_grad():
        while len(graphs) < request.num_graphs:
            b = min(batch_size, request.num_graphs - len(graphs))
            indices = rng.integers(0, len(basis_adj), size=b)
            donor_adj = basis_adj[indices]
            donor_n = basis_n[indices]
            sample_x, soft, lam, u = sample_batch(
                model_x,
                model_lam,
                donor_adjacencies=donor_adj,
                donor_sizes=donor_n,
                sde_x=sde_x,
                sde_lam=sde_lam,
                sample_cfg=sample_cfg,
                eigen_mask_mode="laplacian_nonzero_prefix",
                spectral_operator="combinatorial_laplacian",
                spectral_transform=spectral_transform,
                device=device,
                generator=topology_generator,
            )
            soft = 0.5 * (soft + soft.transpose(-1, -2))
            nmax = soft.size(1)
            flags = (
                torch.arange(nmax, device=device).unsqueeze(0)
                < donor_n.to(device).unsqueeze(1)
            ).float()
            topology_state = _operator_eigenvalues_to_spectral_state(
                lam,
                flags,
                spectral_operator="combinatorial_laplacian",
                spectral_transform=spectral_transform,
            )
            eye = torch.eye(nmax, device=device, dtype=torch.bool).unsqueeze(0)
            discrete = (
                (soft > threshold)
                & ~eye
                & flags.bool().unsqueeze(1)
                & flags.bool().unsqueeze(2)
            )
            discrete = discrete | discrete.transpose(1, 2)
            state_hashes = [
                hierarchical._tensor_state_digest(
                    sample_x[row],
                    soft[row],
                    flags[row],
                    u[row],
                    topology_state[row],
                    lam[row],
                    discrete[row],
                )
                for row in range(b)
            ]
            topology_out = model_lam.forward_topology(
                sample_x, soft, flags, u, topology_state
            )
            (
                node_index,
                edge_index,
                attribute_out,
                batch_attribute_rows,
                batch_trajectories,
            ) = _attribute_diffusion_decode(
                model_lam,
                discrete,
                flags,
                donor_n.to(device),
                spectral_transform,
                vocab,
                attr_cfg,
                diffusion_cfg,
                diffusion_schema,
                generator=attribute_generator,
            )
            for row in range(b):
                if state_hashes[row] != hierarchical._tensor_state_digest(
                    sample_x[row],
                    soft[row],
                    flags[row],
                    u[row],
                    topology_state[row],
                    lam[row],
                    discrete[row],
                ):
                    raise AssertionError("Attribute diffusion modified topology-generation inputs")

            topology_summaries = model_lam.topology_structure_means_from_outputs(
                topology_out
            )
            typed_summaries = model_lam.attribute_structure_means_from_outputs(
                attribute_out
            )
            endpoint_node_posterior = attribute_out["endpoint_node_posterior"]
            endpoint_bond_posterior = attribute_out["endpoint_bond_posterior"]

            for row in range(b):
                size = int(donor_n[row])
                topology_matrix = discrete[row, :size, :size]
                topology_graph = nx.from_numpy_array(
                    topology_matrix.cpu().numpy().astype(np.int8)
                )
                graph = nx.Graph()
                for node in range(size):
                    graph.add_node(
                        node,
                        **{
                            str(vocab.node_attribute): vocab.node_value(
                                int(node_index[row, node])
                            )
                        },
                    )
                upper = topology_matrix.triu(1).nonzero(as_tuple=False)
                for left, right in upper.tolist():
                    graph.add_edge(
                        int(left),
                        int(right),
                        **{
                            str(vocab.edge_attribute): vocab.edge_value(
                                int(edge_index[row, left, right]) + 1
                            )
                        },
                    )
                if set(graph.edges()) != set(topology_graph.edges()):
                    raise AssertionError("Serialized attributed graph differs from fixed topology")

                index = int(indices[row])
                graph_index = len(graphs)
                diagnostic = batch_attribute_rows[row]
                diagnostic.update({
                    "graph_index": graph_index,
                    "node_confidence_mean": float(
                        endpoint_node_posterior[row, :size].max(-1).values.mean().cpu()
                    ),
                    "edge_confidence_mean": (
                        float(
                            endpoint_bond_posterior[row, :size, :size][
                                topology_matrix
                            ].max(-1).values.mean().cpu()
                        )
                        if bool(topology_matrix.any()) else None
                    ),
                    "connected": nx.is_connected(topology_graph),
                    "topology_state_sha256": state_hashes[row],
                    "posthoc_repair": False,
                    "rewiring": False,
                })
                graph.graph["attribute_diffusion"] = {
                    "steps": int(diffusion_cfg["steps"]),
                    "sample_steps": int(diffusion_cfg["sample_steps"]),
                    "constraint_mode": str(
                        attr_cfg.get("decode", {}).get("constraint_mode", "none")
                    ),
                    "topology_state_sha256": state_hashes[row],
                    "edge_head_includes_no_edge": False,
                    "posthoc_repair": False,
                }
                graphs.append(graph)
                topology_graphs.append(topology_graph)
                matrix = soft[row, :size, :size].cpu().numpy().astype(np.float64)
                np.fill_diagonal(matrix, 0)
                continuous.append(matrix)
                spectra.append(lam[row].cpu().numpy().astype(np.float64))
                basis_indices.append(index)
                topology_hashes.append(state_hashes[row])
                attribute_rows.append(diagnostic)
                if bool(diffusion_cfg.get("save_trajectory", False)):
                    trajectories.append(batch_trajectories[row])

                topology_prediction = {
                    "graph_index": graph_index,
                    **{
                        key: value[row].cpu().numpy().astype(np.float64)
                        for key, value in topology_summaries.items()
                    },
                }
                typed_prediction = {
                    "graph_index": graph_index,
                    **{
                        key: value[row].cpu().numpy().astype(np.float64)
                        for key, value in typed_summaries.items()
                    },
                }
                topology_predictions.append(topology_prediction)
                typed_predictions.append(typed_prediction)
                combined_predictions.append({
                    "graph_index": graph_index,
                    **{
                        f"topology_{key}": value
                        for key, value in topology_prediction.items()
                        if key != "graph_index"
                    },
                    **{
                        key: value
                        for key, value in typed_prediction.items()
                        if key != "graph_index"
                    },
                })
            print(
                f"Hybrid-attributed-loggap generated {len(graphs)}/{request.num_graphs}",
                flush=True,
            )

    aggregate: dict[str, Any] = {
        "num_requested": request.num_graphs,
        "num_generated": len(graphs),
        "num_filtered": 0,
        "num_topology_resampled": 0,
        "attribute_diffusion_steps": int(diffusion_cfg["steps"]),
        "attribute_sampling_steps": int(diffusion_cfg["sample_steps"]),
        "node_confidence_mean": float(
            np.mean([row["node_confidence_mean"] for row in attribute_rows])
        ),
        "constraint_mode": attr_cfg.get("decode", {}).get("constraint_mode", "none"),
        "edge_head_includes_no_edge": False,
    }
    finite_edge = [
        row["edge_confidence_mean"]
        for row in attribute_rows
        if row["edge_confidence_mean"] is not None
    ]
    aggregate["edge_confidence_mean"] = (
        float(np.mean(finite_edge)) if finite_edge else None
    )
    for key in (
        "topology_infeasible",
        "atom_degree_incompatible",
        "bond_valence_exceeded",
        "capacity_constraints_satisfied",
        "topology_preserved",
        "connected",
    ):
        values = [bool(row[key]) for row in attribute_rows if key in row]
        aggregate[key + "_count"] = sum(values)
        aggregate[key + "_denominator"] = len(values)
        aggregate[key + "_rate"] = float(np.mean(values)) if values else None
    for key in (
        "atom_constraint_activations",
        "bond_constraint_activations",
        "node_category_change_count",
        "bond_category_change_count",
    ):
        aggregate[key] = int(sum(int(row.get(key, 0)) for row in attribute_rows))

    target.parent.mkdir(parents=True, exist_ok=True)
    staging = Path(
        tempfile.mkdtemp(prefix=".gdsm_hybrid_attr_generate_", dir=target.parent)
    )
    try:
        payloads: dict[str, Any] = {
            "base_graphs": graphs,
            "molecular_graphs": graphs,
            "topology_graphs": topology_graphs,
            "continuous_adjacencies": continuous,
            "sampled_spectra": spectra,
            "sampled_basis_indices": basis_indices,
            "predicted_topology_summaries": topology_predictions,
            "predicted_typed_graphlet_summaries": typed_predictions,
            "predicted_structure_summaries": combined_predictions,
        }
        if bool(diffusion_cfg.get("save_trajectory", False)):
            payloads["attribute_diffusion_trajectories"] = trajectories
        files: dict[str, dict[str, Any]] = {}
        for name, data in payloads.items():
            path = staging / (name + ".pkl")
            with path.open("wb") as handle:
                pickle.dump(data, handle, protocol=pickle.HIGHEST_PROTOCOL)
            files[name] = {"path": path.name, "sha256": _sha256(path)}
        files["base_graphs"]["role"] = "final_attributed_graphs"
        files["molecular_graphs"]["role"] = "compatibility_alias"
        files["topology_graphs"]["role"] = "fixed_binary_topologies_before_attributes"
        files["predicted_topology_summaries"].update({
            "topology_only_graphlets": True,
            "orbit_summary": bool(state["topology_summary"].get("orbit_enabled", False)),
        })
        files["predicted_typed_graphlet_summaries"]["typed_graphlets"] = True
        files["predicted_structure_summaries"]["role"] = (
            "combined_hierarchical_predictions"
        )
        diagnostics_path = staging / "attribute_diffusion_diagnostics.json"
        _write_json(
            diagnostics_path,
            {"per_graph": attribute_rows, "aggregate": aggregate},
        )
        pairing_path = staging / "topology_pairing.json"
        _write_json(
            pairing_path,
            {
                "format": "gdsm_hybrid_attributed_topology_pairing_v1",
                "hash_inputs": [
                    "sample_x",
                    "soft_adjacency",
                    "flags",
                    "eigenbasis",
                    "spectral_state",
                    "eigenvalues",
                    "binary_topology",
                ],
                "per_graph_sha256": topology_hashes,
                "batch_size": batch_size,
                "generation_seed": request.generation_seed,
                "checkpoint_sha256": _sha256(request.checkpoint_path),
            },
        )
        files["attribute_diffusion_diagnostics"] = {
            "path": diagnostics_path.name,
            "sha256": _sha256(diagnostics_path),
        }
        files["topology_pairing"] = {
            "path": pairing_path.name,
            "sha256": _sha256(pairing_path),
        }
        _write_json(
            staging / "manifest.json",
            {
                "format": GENERATION_FORMAT,
                "model_id": wrapper.model_id,
                "variant": state["variant"],
                "run_id": request.run.run_id,
                "generation_id": request.resolved_generation_id,
                "generation_seed": request.generation_seed,
                "num_requested": request.num_graphs,
                "num_generated": len(graphs),
                "num_filtered": 0,
                "num_topology_resampled": 0,
                "duration_seconds": time.monotonic() - started,
                **files,
                "attribute_diffusion_training_contract": state.get(
                    "attribute_diffusion_training_contract"
                ),
                "architecture_contract": state.get("architecture_contract"),
                "checkpoint": {
                    "path": str(request.checkpoint_path.resolve()),
                    "sha256": _sha256(request.checkpoint_path),
                },
                "sampling": {
                    "factorization": "p(A) p(X,R|A)",
                    "topology": "Laplacian_log_gap_reverse_diffusion",
                    "topology_auxiliary_supervision": [
                        "topology_only_connected_induced_graphlets_k3_k4_k5",
                        "ORCA_orbit_histogram_and_log_total",
                    ],
                    "attribute_process": "fixed_topology_marginal_categorical_reverse_diffusion",
                    "attribute_diffusion_steps": int(diffusion_cfg["steps"]),
                    "attribute_sampling_steps": int(diffusion_cfg["sample_steps"]),
                    "attribute_schedule": "cosine_exact_terminal",
                    "categorical_posterior": "clean_endpoint_mixture_exact_skip_posterior",
                    "attribute_auxiliary_supervision": "typed_connected_induced_graphlets_k3_k4_k5",
                    "topology_attribute_encoder_sharing": False,
                    "edge_attributes": "real_bond_type_diffusion_on_generated_edges_only",
                    "edge_head_includes_no_edge": False,
                    "topology_graphlet_supervision": True,
                    "typed_graphlet_supervision": True,
                    "endpoint_constraint": "final_reverse_transition",
                    "node_decode_mode": attr_cfg.get("decode", {}).get(
                        "node_mode", "sample"
                    ),
                    "edge_decode_mode": attr_cfg.get("decode", {}).get(
                        "edge_mode", "sample"
                    ),
                    "node_temperature": float(
                        attr_cfg.get("decode", {}).get("node_temperature", 1.0)
                    ),
                    "edge_temperature": float(
                        attr_cfg.get("decode", {}).get("edge_temperature", 0.6)
                    ),
                    "constraint_mode": attr_cfg.get("decode", {}).get(
                        "constraint_mode", "atom_bond_valence"
                    ),
                    "edge_order": attr_cfg.get("decode", {}).get(
                        "edge_order", "random"
                    ),
                    "infeasible_policy": attr_cfg.get("decode", {}).get(
                        "infeasible_policy", "retain"
                    ),
                    "separate_attribute_rng": separate_rng,
                    "topology_seed": request.generation_seed,
                    "attribute_seed": attribute_seed,
                    "generation_batch_size": batch_size,
                    "topology_preserved_during_attribute_diffusion": True,
                    "degree_sequence_prescribed_during_topology_diffusion": False,
                    "connectivity_guaranteed": False,
                    "full_chemical_validity_guaranteed": False,
                    "rewiring": False,
                    "posthoc_repair": False,
                    "filtering": False,
                    "replacement_sampling": False,
                },
            },
        )
        if target.exists():
            shutil.rmtree(target)
        staging.replace(target)
    except BaseException:
        shutil.rmtree(staging, ignore_errors=True)
        raise
    return GenerationArtifacts(
        run_dir=layout.run_dir,
        generation_dir=target,
        graphs_path=target / "base_graphs.pkl",
        manifest_path=target / "manifest.json",
        num_requested=request.num_graphs,
        num_generated=len(graphs),
        graphs_sha256=_sha256(target / "base_graphs.pkl"),
    )

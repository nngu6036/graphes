class HybridAttributedSpectrumPPGNScore(hierarchical.AttributedSpectrumPPGNScore):
    """Separate topology PPGN and time-conditioned fixed-topology attribute PPGN."""

    def __init__(self, *args: Any, attribute_time_conditioning: bool = True, **kwargs: Any) -> None:
        super().__init__(*args, **kwargs)
        if not attribute_time_conditioning:
            raise ValueError("Hybrid attribute diffusion requires explicit time conditioning")

        # The hierarchical predecessor reserves an extra MASK channel.  Marginal
        # diffusion has only real categories at every state, so rebuild the
        # attribute input projection without a mask/no-edge channel.
        self.node_input_classes = self.node_classes
        self.edge_input_classes = self.edge_classes
        topology_node_dim = self.max_feat_num + self.rw_steps
        attribute_node_dim = topology_node_dim + self.node_input_classes
        attribute_pair_dim = 2 + self.sp_dim + attribute_node_dim + self.edge_input_classes
        self.attribute_pair_input = nn.Linear(attribute_pair_dim, self.ppgn_hidden_dim)
        self.attribute_pair_input_norm = nn.LayerNorm(self.ppgn_hidden_dim)
        self.attribute_time_mlp = nn.Sequential(
            nn.Linear(self.ppgn_hidden_dim, self.ppgn_hidden_dim),
            nn.SiLU(),
            nn.Linear(self.ppgn_hidden_dim, self.ppgn_hidden_dim),
        )

    def attribute_parameters(self):
        yield from super().attribute_parameters()
        yield from self.attribute_time_mlp.parameters()

    def categorical_attribute_inputs(
        self,
        flags: torch.Tensor,
        support: torch.Tensor,
        node_state: torch.Tensor,
        edge_state: torch.Tensor,
    ) -> tuple[torch.Tensor, torch.Tensor]:
        b, n = flags.shape
        if node_state.shape != (b, n):
            raise ValueError("node_state must have shape [B,N]")
        if edge_state.shape != (b, n, n):
            raise ValueError("edge_state must have shape [B,N,N]")
        active = flags.bool()
        if support.dtype != torch.bool or support.shape != edge_state.shape:
            raise ValueError("support must be boolean [B,N,N]")
        if not torch.equal(support, support.transpose(1, 2)):
            raise ValueError("fixed topology support must be symmetric")
        eye = torch.eye(n, dtype=torch.bool, device=flags.device).unsqueeze(0)
        valid_pairs = active.unsqueeze(1) & active.unsqueeze(2) & ~eye
        if bool((support & ~valid_pairs).any()):
            raise ValueError("fixed topology support contains padded pairs or loops")
        if bool(((node_state < 0) | (node_state >= self.node_classes))[active].any()):
            raise ValueError("node_state contains an out-of-vocabulary category")
        if bool(((edge_state < 0) | (edge_state >= self.edge_classes))[support].any()):
            raise ValueError("edge_state contains an out-of-vocabulary bond category")

        node_attr = F.one_hot(
            node_state.clamp(min=0, max=self.node_classes - 1), self.node_classes
        ).to(flags.dtype)
        node_attr = node_attr * active.unsqueeze(-1).to(node_attr.dtype)
        edge_attr = F.one_hot(
            edge_state.clamp(min=0, max=self.edge_classes - 1), self.edge_classes
        ).to(flags.dtype)
        edge_attr = edge_attr * support.unsqueeze(-1).to(edge_attr.dtype)
        return node_attr, edge_attr

    def _encode_attributes(
        self,
        x: torch.Tensor,
        adj: torch.Tensor,
        flags: torch.Tensor,
        eigenvalues: torch.Tensor,
        *,
        node_attr: torch.Tensor | None = None,
        edge_attr: torch.Tensor | None = None,
        attribute_time: torch.Tensor | None = None,
    ) -> tuple[torch.Tensor, torch.Tensor, torch.Tensor]:
        if node_attr is None or edge_attr is None:
            raise ValueError("Hybrid attribute diffusion requires explicit categorical states")
        if attribute_time is None or attribute_time.shape != (flags.shape[0],):
            raise ValueError("attribute_time must have shape [B]")
        binary, node, _sp, base = self._base_parts(x, adj, flags)
        node = torch.cat((node, node_attr), dim=-1)
        pair = torch.cat((base, self._diag_pair(node), edge_attr), dim=-1)
        pair_mask = flags.to(pair.dtype).unsqueeze(-1) * flags.to(pair.dtype).unsqueeze(-2)
        h = F.elu(self.attribute_pair_input_norm(self.attribute_pair_input(pair)))
        time_context = self.attribute_time_mlp(
            sinusoidal_time_embedding(attribute_time.float(), self.ppgn_hidden_dim)
        )
        h = (h + time_context[:, None, None, :]) * pair_mask.unsqueeze(-1)
        for layer in self.attribute_ppgn_layers:
            h = layer(h, pair_mask, flags)
        shared, _ = self._pool_pair(h, flags, eigenvalues)
        return shared, h, binary

    def forward_attributes(
        self,
        x: torch.Tensor,
        adj: torch.Tensor,
        flags: torch.Tensor,
        eigenvectors: torch.Tensor,
        eigenvalues: torch.Tensor,
        *,
        node_attr: torch.Tensor | None = None,
        edge_attr: torch.Tensor | None = None,
        attribute_time: torch.Tensor | None = None,
    ) -> dict[str, torch.Tensor]:
        del eigenvectors
        shared, pair_h, _binary = self._encode_attributes(
            x,
            adj,
            flags,
            eigenvalues,
            node_attr=node_attr,
            edge_attr=edge_attr,
            attribute_time=attribute_time,
        )
        n = pair_h.size(1)
        idx = torch.arange(n, device=pair_h.device)
        diag = pair_h[:, idx, idx, :]
        sym_pair = 0.5 * (pair_h + pair_h.transpose(1, 2))
        outputs = {
            "typed_graphlet_logits": self.typed_graphlet_logits(shared),
            "typed_graphlet_mass_logits": self.typed_graphlet_mass_logits(shared),
            "node_logits": self.node_category_head(diag),
            "edge_logits": self.edge_category_head(sym_pair),
        }
        for name, value in outputs.items():
            if not torch.isfinite(value).all():
                raise FloatingPointError(f"Non-finite {name} from hybrid attribute PPGN")
        return outputs


def _fit_attribute_diffusion_schema(
    node_labels: torch.Tensor,
    edge_labels: torch.Tensor,
    *,
    node_classes: int,
    edge_classes: int,
    pseudocount: float,
) -> dict[str, Any]:
    node_valid = node_labels >= 0
    node_counts = torch.bincount(
        node_labels[node_valid], minlength=int(node_classes)
    ).to(torch.float64)
    n = edge_labels.shape[1]
    upper = torch.triu(
        torch.ones((n, n), dtype=torch.bool, device=edge_labels.device), diagonal=1
    ).unsqueeze(0)
    edge_valid = (edge_labels >= 0) & upper
    edge_counts = torch.bincount(
        edge_labels[edge_valid], minlength=int(edge_classes)
    ).to(torch.float64)
    node_smoothed = node_counts + float(pseudocount)
    edge_smoothed = edge_counts + float(pseudocount)
    return {
        "node_category_counts": node_counts.to(torch.long).tolist(),
        "bond_category_counts": edge_counts.to(torch.long).tolist(),
        "node_marginal": (node_smoothed / node_smoothed.sum()).tolist(),
        "bond_marginal": (edge_smoothed / edge_smoothed.sum()).tolist(),
        "bond_head_includes_no_edge": False,
        "bond_domain": "clean_present_unordered_topology_edges_only",
        "source": "training_split_only",
    }


def _attribute_noise_models(
    schema: Mapping[str, Any], cfg: Mapping[str, Any], device: torch.device
) -> tuple[torch.Tensor, MarginalNoise, MarginalNoise]:
    schedule = cosine_alpha_bar(int(cfg["steps"]), device=device)
    return (
        schedule,
        MarginalNoise(schema["node_marginal"], schedule),
        MarginalNoise(schema["bond_marginal"], schedule),
    )


def _sample_upper_categories(
    probabilities: torch.Tensor,
    support: torch.Tensor,
    generator: torch.Generator,
) -> torch.Tensor:
    if probabilities.shape[:-1] != support.shape:
        raise ValueError("Probability and fixed-support shapes differ")
    result = torch.zeros_like(support, dtype=torch.long)
    upper = support & torch.ones_like(support).triu(1)
    if bool(upper.any()):
        sampled = draw_categories(probabilities[upper], generator)
        result[upper] = sampled
        result = result + result.transpose(1, 2)
    return result


def _draw_noisy_attributes(
    node_labels: torch.Tensor,
    edge_labels: torch.Tensor,
    flags: torch.Tensor,
    support: torch.Tensor,
    t: torch.Tensor,
    node_noise: MarginalNoise,
    bond_noise: MarginalNoise,
    generator: torch.Generator,
) -> tuple[torch.Tensor, torch.Tensor]:
    node_probs = node_noise.forward_probs(node_labels.clamp_min(0), t)
    nodes = draw_categories(node_probs, generator).masked_fill(~flags.bool(), 0)
    bond_probs = bond_noise.forward_probs(edge_labels.clamp_min(0), t)
    bonds = _sample_upper_categories(bond_probs, support, generator)
    return nodes, bonds


def _categorical_diffusion_loss(
    outputs: Mapping[str, torch.Tensor],
    node_labels: torch.Tensor,
    edge_labels: torch.Tensor,
    flags: torch.Tensor,
    support: torch.Tensor,
) -> tuple[torch.Tensor, torch.Tensor, dict[str, float]]:
    node_selected = flags.bool() & (node_labels >= 0)
    upper = support & torch.ones_like(support).triu(1)

    def selected_loss(logits: torch.Tensor, labels: torch.Tensor, selected: torch.Tensor):
        if bool(selected.any()):
            loss = F.cross_entropy(logits[selected], labels[selected])
            accuracy = (logits[selected].argmax(-1) == labels[selected]).float().mean()
            return loss, float(accuracy.detach())
        return logits.sum() * 0.0, 0.0

    node_ce, node_accuracy = selected_loss(
        outputs["node_logits"], node_labels, node_selected
    )
    edge_ce, edge_accuracy = selected_loss(
        outputs["edge_logits"], edge_labels, upper
    )
    return node_ce, edge_ce, {
        "node_accuracy": node_accuracy,
        "edge_accuracy": edge_accuracy,
        "node_supervised_count": float(node_selected.sum()),
        "edge_supervised_count": float(upper.sum()),
    }


def _loss_batch(
    model_x,
    model_lam: HybridAttributedSpectrumPPGNScore,
    batch: tuple[torch.Tensor, ...],
    *,
    sde_x,
    sde_lam,
    eps: float,
    eigen_mask_mode: str,
    spectral_transform: Mapping[str, Any],
    topology_summary_cfg: Mapping[str, Any],
    attribute_summary_cfg: Mapping[str, Any],
    attr_cfg: Mapping[str, Any],
    attribute_diffusion_cfg: Mapping[str, Any],
    node_noise: MarginalNoise,
    bond_noise: MarginalNoise,
    generator: torch.Generator,
) -> tuple[torch.Tensor, dict[str, float]]:
    (
        x0,
        adj0,
        flags,
        _sizes,
        u,
        lam0,
        node_labels,
        edge_labels,
        topology_gh,
        topology_gm,
        topology_ch,
        topology_oh,
        topology_ot,
        typed_gh,
        typed_gm,
    ) = batch
    b = x0.size(0)
    state0 = _operator_eigenvalues_to_spectral_state(
        lam0,
        flags,
        spectral_operator="combinatorial_laplacian",
        spectral_transform=spectral_transform,
    )

    # Continuous topology diffusion branch.
    topology_t = torch.rand((b,), device=x0.device, generator=generator) * (1 - eps) + eps
    zx = mask_x(
        torch.randn(x0.shape, device=x0.device, generator=generator), flags
    )
    eigen_mask = eigen_mask_from_flags(flags, eigen_mask_mode)
    zs = torch.randn(state0.shape, device=x0.device, generator=generator) * eigen_mask
    mean_x, std_x = sde_x.marginal_x(x0, topology_t)
    xt = mask_x(mean_x + std_x[:, None, None] * zx, flags)
    mean_s, std_s = sde_lam.marginal_spectrum(state0, topology_t)
    st = (mean_s * eigen_mask + std_s[:, None] * zs) * eigen_mask
    lam_t = _spectral_state_to_operator_eigenvalues(
        st,
        flags,
        spectral_operator="combinatorial_laplacian",
        spectral_transform=spectral_transform,
    )
    operator_t = reconstruct_adjacency(u, lam_t)
    adj_t = hierarchical._operator_to_adjacency_state(
        operator_t, flags, "combinatorial_laplacian"
    )
    pred_x = model_x(xt, adj_t, flags, u, st)
    topology_out = model_lam.forward_topology(xt, adj_t, flags, u, st)

    # Fixed clean topology attribute diffusion branch.  The support comes from
    # clean present bonds and must match the clean binary topology exactly.
    n = adj0.size(1)
    eye = torch.eye(n, dtype=torch.bool, device=adj0.device).unsqueeze(0)
    clean_binary = (
        (adj0 > 0.5)
        & flags.bool().unsqueeze(1)
        & flags.bool().unsqueeze(2)
        & ~eye
    )
    clean_binary = clean_binary | clean_binary.transpose(1, 2)
    support = edge_labels >= 0
    if not torch.equal(support, clean_binary):
        raise AssertionError("Clean bond labels and topology support differ")
    total_attr_steps = int(attribute_diffusion_cfg["steps"])
    attribute_t = torch.randint(
        1,
        total_attr_steps + 1,
        (b,),
        device=x0.device,
        generator=generator,
    )
    noisy_nodes, noisy_bonds = _draw_noisy_attributes(
        node_labels,
        edge_labels,
        flags,
        support,
        attribute_t,
        node_noise,
        bond_noise,
        generator,
    )
    node_in, edge_in = model_lam.categorical_attribute_inputs(
        flags, support, noisy_nodes, noisy_bonds
    )
    attribute_out = model_lam.forward_attributes(
        x0,
        clean_binary.to(adj0.dtype),
        flags,
        u,
        state0,
        node_attr=node_in,
        edge_attr=edge_in,
        attribute_time=attribute_t.to(torch.float32) / float(total_attr_steps),
    )

    loss_x = 0.5 * (pred_x - zx).square().reshape(b, -1).sum(dim=-1).mean()
    loss_spectrum = 0.5 * (
        ((topology_out["spectrum"] - zs) * eigen_mask)
        .square()
        .reshape(b, -1)
        .sum(dim=-1)
    ).mean()
    topology_loss, metrics = hierarchical._topology_structure_loss(
        model_lam,
        topology_out,
        topology_gh,
        topology_gm,
        topology_ch,
        topology_oh,
        topology_ot,
        topology_summary_cfg,
    )
    typed_loss, typed_metrics = hierarchical._typed_graphlet_loss(
        model_lam,
        attribute_out,
        typed_gh,
        typed_gm,
        attribute_summary_cfg,
    )
    metrics.update(typed_metrics)
    node_ce, edge_ce, categorical_metrics = _categorical_diffusion_loss(
        attribute_out,
        node_labels,
        edge_labels,
        flags,
        support,
    )
    metrics.update(categorical_metrics)
    total = (
        loss_x
        + loss_spectrum
        + float(topology_summary_cfg.get("loss_weight", 0.10)) * topology_loss
        + float(attribute_summary_cfg.get("loss_weight", 0.10)) * typed_loss
        + float(attr_cfg.get("node_loss_weight", 1.0)) * node_ce
        + float(attr_cfg.get("edge_loss_weight", 1.0)) * edge_ce
    )
    metrics.update({
        "loss_x": float(loss_x.detach()),
        "loss_spectrum": float(loss_spectrum.detach()),
        "topology_structure_loss": float(topology_loss.detach()),
        "attribute_typed_graphlet_loss": float(typed_loss.detach()),
        "node_ce": float(node_ce.detach()),
        "edge_ce": float(edge_ce.detach()),
        "attribute_time_mean": float(attribute_t.float().mean().detach()),
        "attribute_time_fraction_mean": float(
            (attribute_t.float() / float(total_attr_steps)).mean().detach()
        ),
    })
    return total, metrics


def _build_models(
    model_cfg: Mapping[str, Any],
    topology_meta: Mapping[str, Any],
    attribute_meta: Mapping[str, Any],
    device: torch.device,
):
    structural_features = copy.deepcopy(
        dict(model_cfg.get("structural_features", {}) or {})
    )
    model_x = hierarchical.GSDMNodeScore(
        max_feat_num=int(model_cfg["max_feat_num"]),
        hidden_dim=int(model_cfg["hidden_dim"]),
        depth=int(model_cfg["depth"]),
        structural_features=structural_features,
    ).to(device)
    model_lam = HybridAttributedSpectrumPPGNScore(
        **dict(model_cfg),
        topology_graphlet_slices=tuple(
            tuple(int(v) for v in pair)
            for pair in topology_meta["graphlet_slices"]
        ),
        typed_graphlet_slices=tuple(
            tuple(int(v) for v in pair)
            for pair in attribute_meta["graphlet_slices"]
        ),
        topology_clustering_bins=(
            int(topology_meta["clustering_bins"])
            if topology_meta.get("clustering_enabled") else 0
        ),
        topology_orbit_width=(
            int(topology_meta["orbit_width"])
            if topology_meta.get("orbit_enabled") else 0
        ),
    ).to(device)
    return model_x, model_lam



def train(
    wrapper, request: TrainRequest, options: Mapping[str, Any]
) -> TrainingArtifacts:
    validate_options(options)
    if request.run.dataset_id not in {"qm9", "zinc", "attributed"}:
        raise ValueError("Hybrid attributed pipeline is for attributed/molecular datasets")

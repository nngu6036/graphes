def validate_options(options: Mapping[str, Any]) -> None:
    variant = str(options.get("variant", "")).lower()
    if variant not in VARIANTS:
        raise ValueError(
            "Hybrid attributed pipeline requires "
            "vanilla_laplacian_loggap_hybrid_categorical_attributed_ppgn"
        )
    # Reuse all topology, summary, vocabulary, and endpoint validation from the
    # hierarchical model under its canonical variant name.
    hierarchical_options = copy.deepcopy(dict(options))
    hierarchical_options["variant"] = "vanilla_laplacian_loggap_hierarchical_attributed_ppgn"
    hierarchical_options.setdefault("attributed", {}).setdefault(
        "corruption",
        {
            "mask_probability_min": 0.15,
            "mask_probability_max": 0.95,
            "full_mask_probability": 0.25,
        },
    )
    hierarchical.validate_options(hierarchical_options)

    cfg = dict(options.get("attribute_diffusion", {}) or {})
    allowed = {
        "enabled", "steps", "sample_steps", "noise", "schedule", "pseudocount",
        "objective", "endpoint_constraint", "save_trajectory",
    }
    unknown = sorted(set(cfg) - allowed)
    if unknown:
        raise ValueError(f"Unknown attribute_diffusion settings: {unknown}")
    if not bool(cfg.get("enabled", False)):
        raise ValueError("attribute_diffusion.enabled must be true")
    steps = int(cfg.get("steps", 0))
    sample_steps = int(cfg.get("sample_steps", steps))
    if steps < 2:
        raise ValueError("attribute_diffusion.steps must be >= 2")
    if sample_steps < 1 or sample_steps > steps:
        raise ValueError("attribute_diffusion.sample_steps must be in [1, steps]")
    if str(cfg.get("noise", "marginal")) != "marginal":
        raise ValueError("Hybrid attributes use marginal categorical noise only")
    if str(cfg.get("schedule", "cosine_exact_terminal")) != "cosine_exact_terminal":
        raise ValueError("Hybrid attributes require cosine_exact_terminal")
    pseudocount = float(cfg.get("pseudocount", 0.0))
    if not math.isfinite(pseudocount) or pseudocount <= 0:
        raise ValueError("attribute_diffusion.pseudocount must be finite and > 0")
    if str(cfg.get("objective", "")) != "clean_endpoint_cross_entropy":
        raise ValueError("Hybrid attributes use clean_endpoint_cross_entropy")
    if str(cfg.get("endpoint_constraint", "")) != "final_reverse_transition":
        raise ValueError("Chemical constraints are applied in the final reverse transition")
    if bool((options.get("graphlet_refinement", {}) or {}).get("enabled", False)):
        raise ValueError("Hybrid attributed generation does not use rewiring")



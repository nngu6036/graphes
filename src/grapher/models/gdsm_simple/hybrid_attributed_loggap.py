"""Hybrid topology-first GSDM with fixed-topology categorical attribute diffusion.

The model combines the topology branch from the hierarchical attributed
Laplacian log-gap model with the iterative categorical attribute process from
GraphES' joint spectral/categorical implementation.

Design contract
---------------
* Binary topology A is generated first by combinatorial-Laplacian log-gap
  diffusion, supervised by topology-only connected induced graphlets and ORCA
  orbit summaries.
* Once decoded, A is frozen.  Attribute generation cannot add or remove edges.
* Atom categories and real bond categories are generated by an exact-terminal
  marginal categorical diffusion conditioned on A.
* Bond diffusion exists only on present unordered topology edges.  There is no
  learned or sampled ``no-edge`` bond category.
* Typed connected induced graphlets supervise only the attribute branch.
* The final reverse transition applies degree-compatible atom sampling and the
  joint valence-budgeted bond decoder.  This is an intrinsic endpoint
  transition, not RDKit repair, filtering, replacement sampling, or rewiring.
* Topology and attribute PPGN encoders are parameter-disjoint.
"""
